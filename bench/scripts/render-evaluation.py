#!/usr/bin/env python3
"""render-evaluation.py — generate docs/evaluation.md from the latest
Py + TS corpus baselines.

The output is the public scoreboard: per-detector precision / recall /
F1, in-sample AND holdout sections, the lockstep-parity declaration,
and a copy-paste reproduce block.

Discipline:
  - Inputs are the most recent committed baseline JSONs under
    bench/baseline/ — discovered by lex-sort on filenames matching
    YYYY-MM-DD-{py,ts}.json (lex == chronological).
  - The generated file IS committed; the scanner-bench CI gate
    re-runs this script and exits 1 if the file would drift, so
    main always carries the published numbers.
  - No clock reads — measured_at comes from the baseline JSON.

Usage:
    python bench/scripts/render-evaluation.py
    python bench/scripts/render-evaluation.py --out docs/evaluation.md
    python bench/scripts/render-evaluation.py --check       # exit 1 if drift

Exit codes:
    0 — generated (or no drift under --check)
    1 — usage error OR drift detected under --check
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
BASELINE_DIR = REPO_ROOT / "bench" / "baseline"
DEFAULT_OUT = REPO_ROOT / "docs" / "evaluation.md"


def latest_baseline(language: str) -> Path | None:
    """Return the most-recent YYYY-MM-DD-{language}.json path or None."""
    matches = sorted(BASELINE_DIR.glob(f"*-{language}.json"))
    return matches[-1] if matches else None


def fmt_num(x: float | None, places: int = 3) -> str:
    return "n/a" if x is None else f"{x:.{places}f}"


def fmt_pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x * 100:.1f}%"


def render_per_detector_table(per: dict[str, dict[str, Any]]) -> str:
    rows = [
        "| Detector | Precision | Recall | F1 | TP | FP | TN | FN | Support |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for cci, st in per.items():
        rows.append(
            f"| **{cci}** "
            f"| {fmt_num(st['precision'])} "
            f"| {fmt_num(st['recall'])} "
            f"| {fmt_num(st['f1'])} "
            f"| {st['tp']} "
            f"| {st['fp']} "
            f"| {st['tn']} "
            f"| {st['fn']} "
            f"| {st['support']} |"
        )
    return "\n".join(rows)


def render_macro_row(overall: dict[str, Any]) -> str:
    p = overall.get("precision_macro")
    r = overall.get("recall_macro")
    f1 = overall.get("f1_macro")
    return (
        f"| **Macro avg** | **{fmt_num(p)}** | **{fmt_num(r)}** | **{fmt_num(f1)}** "
        f"| — | — | — | — | — |"
    )


def render_engine_section(name: str, doc: dict[str, Any]) -> list[str]:
    out: list[str] = []
    out.append(f"### {name} ({doc['language']}) — measured {doc['measured_at']}\n")
    counts_line = (
        f"- **Corpus:** v{doc['manifest_version']} "
        f"(Top 10 v{doc['top10_version']}) — "
        f"{doc['samples_total']} in-sample samples"
    )
    if doc.get("holdout"):
        counts_line += f" + {doc['holdout']['samples_total']} holdout"
    out.append(counts_line + "\n")
    out.append("#### In-sample\n")
    out.append(render_per_detector_table(doc["per_detector"]))
    out.append("")
    out.append(render_macro_row(doc["overall"]))
    out.append("")
    if doc.get("holdout"):
        out.append("#### Holdout (overfit detector, informational only)\n")
        out.append(render_per_detector_table(doc["holdout"]["per_detector"]))
        out.append("")
        out.append(render_macro_row(doc["holdout"]["overall"]))
        out.append("")
    return out


def render_evaluation(py_doc: dict[str, Any], ts_doc: dict[str, Any]) -> str:
    # Both engines should agree on (tp, fp, tn, fn) per ADR-0023.
    parity_ok = all(
        py_doc["per_detector"].get(cci, {}).get(k) == ts_doc["per_detector"].get(cci, {}).get(k)
        for cci in py_doc["per_detector"]
        for k in ("tp", "fp", "tn", "fn")
    )
    parity_line = (
        "**Lockstep parity (ADR-0023):** Py ↔ TS produce identical "
        "`(tp, fp, tn, fn)` for every detector. ✓"
        if parity_ok
        else "**Lockstep parity (ADR-0023):** DRIFT — Py and TS disagree on "
        "at least one detector's counts. The corpus regression gate will fail."
    )

    lines: list[str] = []
    lines.append("# Evaluation — Context CI scanners on corpus v0.x\n")
    lines.append(
        "> **Status:** AUTO-GENERATED by `bench/scripts/render-evaluation.py`.\n"
        "> Source of truth: the latest committed JSONs under `bench/baseline/`.\n"
        "> The scanner-bench CI gate re-runs this script and fails the build\n"
        "> if this file would drift — so the numbers below are always the\n"
        "> ones our gate just measured.\n"
    )
    lines.append("## What you are looking at\n")
    lines.append(
        "Per-detector precision / recall / F1 for the Context CI Top 10 "
        "scanners measured against the [Adversarial Corpus]"
        "(./corpus-v0.1.md). Two engines run the same corpus and must "
        "produce byte-identical TP / FP / TN / FN counts "
        "([ADR-0023](./decisions/0023-shared-language-runtime.md)) — "
        "any drift is a regression gate failure.\n"
    )
    lines.append(
        "The corpus is split into an **in-sample** slice (used during "
        "detector iteration) and a **holdout** slice (used only by the "
        "gate to detect overfit per "
        "[ADR-0038](./decisions/0038-corpus-v0.2-and-80-20-holdout.md)). "
        "Both are reported below; only the in-sample numbers anchor the "
        "regression contract.\n"
    )
    lines.append(f"{parity_line}\n")
    lines.append("## Per-engine scoreboard\n")
    lines += render_engine_section("Python", py_doc)
    lines += render_engine_section("TypeScript", ts_doc)

    lines.append("## How to reproduce\n")
    lines.append(
        "```bash\n"
        "git clone https://github.com/DevXYZx/primitivehub.git\n"
        "cd primitivehub\n"
        "\n"
        "# Build TS detectors\n"
        "pnpm install --frozen-lockfile\n"
        "cd packages/phub && pnpm build && cd -\n"
        "\n"
        "# Sync Python detectors\n"
        "cd apps/api && uv sync && cd -\n"
        "\n"
        "# Measure both engines + check parity\n"
        "bench/scripts/gate.sh                # exits 0 if no F1 regression > 0.02\n"
        "```\n"
    )
    lines.append(
        "The harness emits per-detector P/R/F1 to stdout and writes today's "
        "baseline under `bench/baseline/`. The committed FLOOR is the "
        "regression contract — see "
        "[`bench/baseline/FLOOR.md`](../bench/baseline/FLOOR.md) for the "
        "discipline and how to declare a recall trade.\n"
    )
    lines.append("## Reading the table\n")
    lines.append(
        "- **TP** — adversarial / borderline-FAIL sample, detector returned "
        "≥ expected verdict.\n"
        "- **FN** — adversarial / borderline-FAIL sample, detector returned "
        "PASS (missed attack).\n"
        "- **FP** — benign sample, detector flagged anyway "
        "(precision hazard).\n"
        "- **TN** — benign sample, detector passed (cleanly silent).\n"
        "- Cross-trip counts (does detector X false-fire on attack family "
        "Y's benign samples?) collapse into the FP / TN dimension only — "
        "we have no ground truth for X on Y-family adversarial content.\n"
    )
    lines.append("## Where to file a missed sample\n")
    lines.append(
        "If you have a primitive that should be caught but isn't, open a "
        "PR adding it to `bench/corpus/samples/<cci-id>/` and an entry to "
        "`bench/corpus/manifest.yaml`. The methodology is documented in "
        "[`docs/false-negative-resolution.md`](./false-negative-resolution.md) "
        "— start at §1 (the four resolution paths) before proposing a fix.\n"
    )
    lines.append(
        "If you have a primitive that's being flagged but shouldn't be, "
        "the false-positive methodology lives at "
        "[`docs/false-positive-resolution.md`](./false-positive-resolution.md) "
        "— same four-path discipline, opposite failure mode.\n"
    )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Render docs/evaluation.md from baselines.")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if the generated content would drift from --out (CI mode).",
    )
    args = parser.parse_args()

    py_path = latest_baseline("py")
    ts_path = latest_baseline("ts")
    if py_path is None or ts_path is None:
        sys.stderr.write(
            f"render-evaluation: missing baselines under {BASELINE_DIR}/\n"
            f"  py: {py_path}\n  ts: {ts_path}\n"
        )
        return 1

    py_doc = json.loads(py_path.read_text())
    ts_doc = json.loads(ts_path.read_text())

    rendered = render_evaluation(py_doc, ts_doc)

    if args.check:
        if not args.out.exists():
            sys.stderr.write(
                f"render-evaluation --check: {args.out} does not exist yet.\n"
                f"Run `python bench/scripts/render-evaluation.py` and commit.\n"
            )
            return 1
        existing = args.out.read_text()
        if existing != rendered:
            sys.stderr.write(
                f"render-evaluation --check: drift detected in {args.out}.\n"
                f"Run `python bench/scripts/render-evaluation.py` and commit.\n"
            )
            return 1
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(rendered)
    sys.stdout.write(f"Wrote {args.out} ({len(rendered)} chars; py={py_path.name}, ts={ts_path.name})\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
