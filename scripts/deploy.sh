#!/usr/bin/env bash
#
# deploy.sh — deploy the PRODUCTION stack to this host. Never `next dev`.
#
# Background: the domain (primitivehub.ai) is fronted by Cloudflare and
# proxied by host nginx → 127.0.0.1:3000. Serving `pnpm dev` there breaks
# (HMR WebSocket → 520) and ships an unminified dev build to real users
# (bugs.md #33). This script always brings up the prod overlay
# (`next start`) and smoke-tests the live edge afterwards.
#
# Two image sources:
#   ghcr   (default) — pull CI-built images from GHCR (source of truth).
#                      Requires a one-time `docker login ghcr.io` on the host.
#   local            — use the image built here (`docker compose build`),
#                      no registry auth. Stopgap until a branch is on main.
#
# Usage:
#   scripts/deploy.sh                 # pull from GHCR, up prod, smoke
#   scripts/deploy.sh local           # use locally-built image, up prod, smoke
#   scripts/deploy.sh local --build    # build web locally first, then deploy
#   scripts/deploy.sh --no-smoke       # skip the post-deploy smoke
#
# Exit: 0 deploy + smoke ok · non-zero on failure.

set -euo pipefail
cd "$(dirname "$0")/.."

MODE="ghcr"
BUILD=0
SMOKE=1
for a in "$@"; do
  case "$a" in
    ghcr|local) MODE="$a" ;;
    --build)    BUILD=1 ;;
    --no-smoke) SMOKE=0 ;;
    *) echo "unknown arg: $a" >&2; exit 2 ;;
  esac
done

FILES=(-f compose.yaml -f compose.prod.yaml)

# The local overlay pins the locally-built image + disables the pull the
# prod overlay would otherwise force. Generated on demand so it needn't be
# committed (it's gitignored).
LOCAL_OVERLAY="compose.deploy-local.yaml"
if [[ "$MODE" == "local" ]]; then
  if [[ ! -f "$LOCAL_OVERLAY" ]]; then
    cat > "$LOCAL_OVERLAY" <<'YAML'
# EPHEMERAL deploy overlay — use the LOCALLY-built prod image instead of
# pulling from GHCR. Generated by scripts/deploy.sh; gitignored.
services:
  web:
    image: ghcr.io/devxyzx/primitivehub-web:latest
    pull_policy: never
YAML
  fi
  FILES+=(-f "$LOCAL_OVERLAY")
fi

echo "==> deploy mode: $MODE"

if [[ "$MODE" == "local" && "$BUILD" == 1 ]]; then
  echo "==> staging repo docs into web build context (bugs.md #25)"
  rm -rf apps/web/docs && cp -r docs apps/web/docs
  echo "==> building web (runner target)"
  docker compose "${FILES[@]}" build web
  rm -rf apps/web/docs
fi

if [[ "$MODE" == "ghcr" ]]; then
  if ! grep -q '"ghcr.io"' "${HOME}/.docker/config.json" 2>/dev/null; then
    echo "!! host is not logged into ghcr.io — run: docker login ghcr.io -u <user>" >&2
    echo "   (or deploy the locally-built image: scripts/deploy.sh local --build)" >&2
    exit 1
  fi
  echo "==> pulling images from GHCR"
  docker compose "${FILES[@]}" pull web api api-worker
fi

echo "==> bringing up prod stack"
docker compose "${FILES[@]}" up -d

echo "==> waiting for web health"
for _ in $(seq 1 30); do
  st=$(docker inspect --format '{{.State.Health.Status}}' primitivehub-web-1 2>/dev/null || echo starting)
  [[ "$st" == "healthy" ]] && break
  sleep 2
done
docker ps --format '{{.Names}}\t{{.Status}}' | grep -E 'web|api'

if [[ "$SMOKE" == 1 ]]; then
  echo "==> post-deploy smoke (live edge)"
  scripts/smoke-prod.sh
fi

echo "==> deploy complete ($MODE)"
